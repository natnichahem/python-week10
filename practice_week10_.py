Orders=[
    {"id":2001,"customer":"Anan","city":"Korat","product":"Keyboard","qty":2,"price":450},
    {"id":2002,"customer":"Benja","city":"Bangkok","product":"Mouse","qty":5,"price":180},
    {"id":2003,"customer":"Chai","city":"Bangkok","product":"Monitor","qty":1,"price":3200},
    {"id":2004,"customer":"Duang","city":"Phuket","product":"Mouse","qty":3,"price":180},
    {"id":2005,"customer":"Anan","city":"Korat","product":"Monitor","qty":2,"price":3200},
    {"id":2006,"customer":"Ekk","city":"Bangkok","product":"Keyboard","qty":4,"price":450}
]

results = []
total = 0

for o in Orders:
    sub = o["qty"] * o["price"]
    vat = sub * 0.07
    net = sub + vat
    results.append((o["id"], vat, net))
    total += net

print("List ของ Tuple (id, vat, ราคารวม vat):")
for r in results:
    print(r)

print(f"\nยอดขายรวม vat สุทธิทั้งหมด: {total:,.2f} บาท")